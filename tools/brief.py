# -*- coding: utf-8 -*-
"""Turn a short natural-language building brief into a reviewable YAML draft.

  python tools/brief.py --project P --text "2010년대 판상형 아파트 25층" --json
  python tools/brief.py --project P --text "2020년대 타워 36층" --glb photos/scan.glb

This is a deterministic parser, not an LLM call. It selects a style from
templates/styles and marks every uncertain field as estimated. An agent or
LLM parser can later fill the same schema; the geometry must still pass the normal
mass/facade gates.
"""
import argparse
import json
import os
import re
import sys

import yaml

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
from proj import ROOT, KIT  # noqa: E402
sys.path.insert(0, KIT)
from templates.facade_style import list_styles, select_style, load_style  # noqa: E402

STYLE_DIR = os.path.join(KIT, "templates", "styles")


def era_of(text):
    m = re.search(r"(19[89]0|2000|2010|2020)\s*년대", text)
    if m:
        return m.group(1) + "s"
    m = re.search(r"\b(19[89]\d|20[0-2]\d)s?\b", text, re.I)
    if m:
        return m.group(1)[:3] + "0s"
    return ""


def type_of(text):
    if any(k in text for k in ("주상복합", "상가", "근린생활", "mixed")):
        return "mixed_use"
    if any(k in text for k in ("판상", "슬라브", "slab", "plate")):
        return "slab_apartment"
    if any(k in text for k in ("타워", "tower")):
        return "tower_apartment"
    return ""


def floors_of(text):
    for pat in (r"(\d{1,3})\s*층", r"(\d{1,3})\s*(?:floors?|F)\b"):
        m = re.search(pat, text, re.I)
        if m:
            return int(m.group(1))
    return None


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--text", required=True)
    ap.add_argument("--out", default="building_brief.yaml")
    ap.add_argument("--glb", default="")
    ap.add_argument("--mass", default="")
    ap.add_argument("--force", action="store_true")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()
    text = a.text.strip()
    if not text:
        raise SystemExit("--text is empty")
    era, btype, floors = era_of(text), type_of(text), floors_of(text)
    styles = list_styles(STYLE_DIR)
    chosen = select_style(styles, era, btype)
    if not chosen:
        raise SystemExit("no usable style in templates/styles")
    style = load_style(chosen["path"])
    estimated = ["palette", "window bay counts", "entrance", "roof equipment"]
    if floors is None:
        floors = 20
        estimated.append("floors")
    confidence = dict(floors="high" if floors_of(text) else "low", style="high" if era and btype else "medium")
    brief = {
        "brief": {
            "text": text,
            "style": style.id,
            "style_label": style.label,
            "era": era or style.era,
            "building_type": btype or style.type,
            "floors": floors,
            "floor_height_m": 2.85,
            "balcony": "expanded" if "확장" in text else "",
            "window": "split" if "입면분할" in text else "",
            "region": next((r for r in ("대구", "서울", "부산", "인천", "대전", "광주") if r in text), ""),
            "confidence": confidence,
            "estimated": estimated,
            "source": "heuristic parser; replace with GLB/photo measurements when available",
            "mass": a.mass or "",
            "glb": a.glb or "",
        },
        "style_summary": {
            "palette": style.palette,
            "window": dict(vars(style.window)),
            "layers": dict(vars(style.layers)),
            "night": dict(vars(style.night)),
        },
        "next_action": {
            "command": None,
            "reason": "review this brief/style, then create or select a project and generate the mass before facade work",
        },
    }
    out = a.out if os.path.isabs(a.out) else os.path.join(ROOT, a.out)
    if os.path.exists(out) and not a.force:
        raise SystemExit(f"output exists: {a.out}; use --force")
    os.makedirs(os.path.dirname(out) or ".", exist_ok=True)
    with open(out, "w", encoding="utf-8") as f:
        yaml.safe_dump(brief, f, allow_unicode=True, sort_keys=False)
    result = dict(status="PASS", text=text, style=style.id, era=brief["brief"]["era"],
                  building_type=brief["brief"]["building_type"], floors=floors,
                  confidence=confidence, estimated=estimated,
                  out=os.path.relpath(out, ROOT).replace(os.sep, "/"),
                  note="heuristic draft; geometry is not generated by this command")
    if a.json:
        print(json.dumps(result, ensure_ascii=False))
    else:
        print(f"[brief] {style.id}  {brief['brief']['era']} {brief['brief']['building_type']} {floors}F -> {a.out}")
        print(f"        estimated: {', '.join(estimated)}")
    return


if __name__ == "__main__":
    main()
