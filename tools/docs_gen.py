# -*- coding: utf-8 -*-
"""Generate docs/agent/TOOL_<name>.md from each tool's --help output.

  python tools/docs_gen.py                  # core tools
  python tools/docs_gen.py --all            # every tools/*.py and tools/qa/*.py
  python tools/docs_gen.py --check --json   # no writes; exit 1 when a doc is stale

The generated file is a thin wrapper around `python tools/<name>.py --help`: the source
docstring and argparse text stay the single source of truth, so a changed option updates
the doc. Tools whose --help fails (missing dependency, required environment) are reported
and skipped rather than written half-correct.
"""
import argparse
import glob
import json
import os
import subprocess
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
KIT = os.path.dirname(HERE)
OUT = os.path.join(KIT, "docs", "agent")

CORE = [
    "agent.py", "cycle.py", "check.py", "render.py", "photo_check.py", "tile_compare.py",
    "facade_read.py", "band_scan.py", "shadow_norm.py", "photo_quality.py",
    "photo_plane_map.py", "glb_shape.py", "lod_auto.py", "compare.py", "sync_branches.py",
    "state.py", "docs_gen.py",
]


def help_text(path):
    r = subprocess.run([sys.executable, path, "--help"], cwd=KIT, capture_output=True,
                       text=True, encoding="utf-8", errors="replace", timeout=30)
    if r.returncode != 0 or not (r.stdout or "").strip():
        return None, (r.returncode, ((r.stdout or "") + (r.stderr or "")).strip()[-400:])
    return r.stdout.strip(), None


def doc_for(path, text):
    rel = os.path.relpath(path, KIT).replace(os.sep, "/")
    stem = os.path.splitext(os.path.basename(path))[0]
    return "\n".join([
        "# %s" % stem,
        "",
        "> Generated by `tools/docs_gen.py` from `python %s --help`." % rel,
        "> Do not edit by hand; change the tool's argparse text and regenerate.",
        "",
        "```text",
        text,
        "```",
        "",
    ])


def main():
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawDescriptionHelpFormatter)
    ap.add_argument("--all", action="store_true", help="every tool under tools/ and tools/qa/")
    ap.add_argument("--tools", nargs="*", help="explicit tool file names")
    ap.add_argument("--check", action="store_true", help="report stale docs; do not write")
    ap.add_argument("--json", action="store_true")
    a = ap.parse_args()

    if a.tools:
        paths = [os.path.join(HERE, t) if not os.path.isabs(t) else t for t in a.tools]
    elif a.all:
        paths = sorted(glob.glob(os.path.join(HERE, "*.py")) +
                       glob.glob(os.path.join(HERE, "qa", "*.py")))
    else:
        paths = [os.path.join(HERE, t) for t in CORE]
    paths = [p for p in paths if os.path.isfile(p) and not os.path.basename(p).startswith("_")]

    os.makedirs(OUT, exist_ok=True)
    written, unchanged, skipped = [], [], []
    for path in paths:
        text, error = help_text(path)
        stem = os.path.splitext(os.path.basename(path))[0]
        if text is None:
            skipped.append({"tool": stem, "error": error})
            continue
        target = os.path.join(OUT, "TOOL_%s.md" % stem)
        content = doc_for(path, text)
        old = None
        if os.path.isfile(target):
            with open(target, encoding="utf-8") as f:
                old = f.read()
        if old == content:
            unchanged.append(stem)
            continue
        if a.check:
            written.append(stem)
            continue
        with open(target, "w", encoding="utf-8") as f:
            f.write(content)
        written.append(stem)

    result = {"status": "STALE" if (a.check and written) else "OK",
              "written": written, "unchanged": unchanged, "skipped": skipped,
              "out": os.path.relpath(OUT, KIT).replace(os.sep, "/")}
    if a.json:
        print(json.dumps(result, ensure_ascii=False))
    else:
        print("[docs] written %d, unchanged %d, skipped %d -> %s"
              % (len(written), len(unchanged), len(skipped), result["out"]))
        for s in skipped:
            print("  SKIP %s (%s)" % (s["tool"], s["error"]))
    return 1 if (a.check and written) else 0


if __name__ == "__main__":
    sys.exit(main())
